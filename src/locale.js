export const CONTROL_NAMES = Object.freeze(controls);
const select = (tag) => /^(en|zh)(?:-|$)/i.exec(tag ?? '')?.[1].toLowerCase();
export const localeKey = 'veldon.hulao.language';
export let language = 'zh';

export function preferredLanguage(request, saved, browserLanguages = []) {
  return [request, saved, ...browserLanguages].map(select).find(Boolean) ?? 'en';
}

export function setLanguage(next) {
  if (next === 'zh' || next === 'en') language = next;
}

export function t(source, values = {}, lang = language) {
  const result = lang === 'en' ? (english[source] ?? source) : source;
  return result.replace(/\{(\w+)\}/g, (token, key) => values[key] ?? token);
}

export const actionName = (id, lang = language) => t(controls[id], {}, lang);
export const sideName = (side, lang = language) => (lang === 'en' ? 'P' + (side + 1) : side + 1 + 'P');
const englishNames = { 吕布: 'Lü Bu', 吕蒙: 'Lü Meng', 糜夫人: 'Lady Mi' };
export const fighterName = (c, lang = language) =>
  lang === 'en' ? (englishNames[c.name] ?? c.roman) : c.name;
export const styleName = (c, lang = language) => (lang === 'en' ? FIGHTERS_EN[c.name].style : c.style);
export const moveName = (c, title, lang = language) => (lang === 'en' ? FIGHTERS_EN[c.name][title] : title);
export const familyName = (c, lang = language) =>
  c.family
    .split(' · ')
    .map((word) => t(word, {}, lang))
    .join(' · ');
export const commandName = (s, lang = language) => s.command.map((id) => actionName(id, lang)).join(' → ');
export function skillDetail(s) {
  return [
    commandName(s),
    t('{n} 段', { n: s.steps.length }),
    ...(s.cost ? [t('{n} 能量', { n: s.cost })] : []),
  ].join(' · ');
}

// Save the original Chinese text once so live switches work in both directions.
export function bindPageLanguage(doc) {
  const fields = [];
  for (const attribute of ['text', 'aria-label', 'placeholder', 'content']) {
    for (const element of doc.querySelectorAll('[data-i18n-' + attribute + ']')) {
      const value = attribute === 'text' ? element.textContent : element.getAttribute(attribute);
      fields.push({ element, attribute, value });
    }
  }
  return () => {
    doc.documentElement.lang = language === 'en' ? 'en' : 'zh-Hans';
    for (const { element, attribute, value } of fields) {
      if (attribute === 'text') element.textContent = t(value);
      else element.setAttribute(attribute, t(value));
    }
    for (const button of doc.querySelectorAll('[data-language-switch]')) {
      const toEnglish = language === 'zh';
      button.lang = toEnglish ? 'en' : 'zh-Hans';
      button.textContent = toEnglish ? 'English' : '简体中文';
      button.setAttribute('aria-label', toEnglish ? 'Switch to English' : '切换为简体中文');
    }
  };
}
